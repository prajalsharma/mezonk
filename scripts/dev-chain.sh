#!/usr/bin/env bash
# Local development chain: anvil fork of Mezo Testnet (chain 31611, real MUSD bytecode),
# MezonkExchange (+ factory, resolution, incentives) deployed with a short local policy, anvil test accounts
# funded with MUSD via storage writes on the fork.
# Nothing here touches the public network. Ctrl-C stops anvil.
set -euo pipefail
cd "$(dirname "$0")/.."
PORT="${PORT:-8545}"
RPC="http://127.0.0.1:$PORT"
FORK="${MEZO_TESTNET_RPC_URL:-https://rpc.test.mezo.org}"
# Well-known anvil test keys (public, local only).
PK0=0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80
A0=0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266 # owner / deployer
A1=0x70997970C51812dc3A010C7d01b50e0d17dc79C8 # resolver
A2=0x3C44CdDdB6a900fa2b585dd299e03d12FA4293BC # arbitrator
A3=0x90F79bf6EB2c4f870365E785982E1f101E93b906 # creator
A7=0x14dC79964da2C08b23698B3D3cc7Ca32193d9955 # curator

# Fork through a retrying proxy (see scripts/rpc-retry-proxy.mjs), pinned to a block the healthy nodes have.
node scripts/rpc-retry-proxy.mjs "$FORK" 8600 &
PROXY=$!
for _ in $(seq 1 20); do cast block-number --rpc-url http://127.0.0.1:8600 >/dev/null 2>&1 && break; sleep 0.3; done
HEAD=0
for _ in $(seq 1 20); do B=$(cast block-number --rpc-url "$FORK" 2>/dev/null || echo 0); [ "$B" -gt "$HEAD" ] && HEAD=$B; done
anvil --fork-url http://127.0.0.1:8600 --fork-block-number "$((HEAD - 2))" --port "$PORT" --chain-id 31611 --silent &
ANVIL=$!
trap 'kill $ANVIL $PROXY 2>/dev/null' EXIT
for _ in $(seq 1 60); do cast block-number --rpc-url "$RPC" >/dev/null 2>&1 && break; sleep 0.5; done
echo "anvil fork up at block $(cast block-number --rpc-url "$RPC")"

cd contracts
# Local policy: short seeding (2h) and live minimum (1h) so every lifecycle state can be reached by warping.
OUT=$(OWNER=$A0 ARBITRATOR=$A2 RESOLVER=$A1 CURATOR=$A7 CREATOR=$A3 \
  MIN_LIVE_DURATION=3600 POLICY_SEEDING_PERIOD=7200 POLICY_MIN_REST=60 \
  POLICY_MIN_BID_DEPTH=50000000000000000000 POLICY_MIN_ASK_DEPTH=50000000000000000000 \
  forge script script/DeployExchange.s.sol --rpc-url "$RPC" --private-key "$PK0" --broadcast --gas-estimate-multiplier 105 2>&1) || true
# The exchange deploy (it creates three child contracts) uses ~9.05M gas; Mezo blocks allow 10M, so the default
# 30% estimate buffer would exceed the block limit. 5% is enough headroom.
ADDR=$(echo "$OUT" | grep -Eo 'MezonkExchange 0x[0-9a-fA-F]{40}' | head -1 | awk '{print $2}')
BLOCK=$(echo "$OUT" | grep -Eo 'deployBlock [0-9]+' | head -1 | awk '{print $2}')
[ -n "$ADDR" ] || { echo "deploy failed:"; echo "$OUT"; exit 1; }
cd ..
echo "MezonkExchange $ADDR at block $BLOCK"

node apps/web/scripts/fund-musd.mjs "$RPC"

# Mezo's BTC price oracle can't run on a fork (it reads chain-native price data), which would make every MUSD loan
# call revert. Swap in an always-fresh $82,000 stand-in (contracts/test/mocks/MockMezoOracle.sol) so /borrow works.
ORACLE_CODE=$(cd contracts && forge inspect MockMezoOracle deployedBytecode)
cast rpc anvil_setCode 0x7b7c000000000000000000000000000000000015 "$ORACLE_CODE" --rpc-url "$RPC" >/dev/null

cat > apps/web/.env.local <<ENV
# Generated by scripts/dev-chain.sh — local fork only.
NEXT_PUBLIC_CHAIN_ID=31611
NEXT_PUBLIC_RPC_URL=$RPC
# MezonkExchange. Factory, resolution and incentives are derived from it (contract nonces 1, 2, 3).
NEXT_PUBLIC_MARKETS_ADDRESS=$ADDR
NEXT_PUBLIC_MARKETS_DEPLOY_BLOCK=$BLOCK
NEXT_PUBLIC_E2E_WALLET=anvil
INDEXER_MODE=embedded
INDEXER_CONFIRMATIONS=0
INDEXER_INTERVAL_MS=2000
PGLITE_DIR=.pglite-local
MEDIA_STORAGE=local
ENV
rm -rf apps/web/.pglite-local
echo "wrote apps/web/.env.local — now run: pnpm dev   (then: pnpm --filter web seed:local)"
wait $ANVIL
