// Exports the compiled exchange ABIs to the web app as typed `as const` modules.
import { readFileSync, writeFileSync } from "node:fs";

const read = (name) =>
  JSON.parse(readFileSync(new URL(`../contracts/out/${name}.sol/${name}.json`, import.meta.url), "utf8")).abi;
const abis = {
  exchangeAbi: read("MezonkExchange"),
  factoryAbi: read("MezonkMarketFactory"),
  resolutionAbi: read("MezonkResolution"),
  incentivesAbi: read("MezonkIncentives"),
};
let out = "// Generated by scripts/export-abi.mjs from contracts/out. Do not edit by hand.\n";
for (const [k, v] of Object.entries(abis)) out += `export const ${k} = ${JSON.stringify(v, null, 2)} as const;\n\n`;
out += "/** Every protocol event, for decoding logs from all four contracts at once. */\n";
out += "export const protocolEventsAbi = [\n  ...exchangeAbi,\n  ...factoryAbi,\n  ...resolutionAbi,\n  ...incentivesAbi,\n].filter((x) => x.type === \"event\");\n";
writeFileSync(new URL("../apps/web/src/lib/contracts/abi.ts", import.meta.url), out);
console.log(`wrote ${Object.values(abis).reduce((n, a) => n + a.length, 0)} ABI entries`);
