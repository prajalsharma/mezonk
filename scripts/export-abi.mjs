// Exports the compiled MezonkMarkets ABI to the web app as a typed `as const` module.
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(
  readFileSync(new URL("../contracts/out/MezonkMarkets.sol/MezonkMarkets.json", import.meta.url), "utf8"),
);
const out = `// Generated by scripts/export-abi.mjs from contracts/out. Do not edit by hand.
export const mezonkMarketsAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync(new URL("../apps/web/src/lib/contracts/abi.ts", import.meta.url), out);
console.log(`wrote ${artifact.abi.length} ABI entries`);
