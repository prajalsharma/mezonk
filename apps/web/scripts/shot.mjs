import { chromium } from "@playwright/test";
const [,, url, out, theme = "light", w = "1280", h = "900", full = "1"] = process.argv;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: +w, height: +h }, colorScheme: theme });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await p.goto(url, { waitUntil: "domcontentloaded", timeout: 180000 });
await p.waitForTimeout(+(process.env.WAIT ?? 12000));
await p.screenshot({ path: out, fullPage: full === "1" });
const overflow = await p.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
console.log(JSON.stringify({ out, overflow, errors: errs.slice(0, 5) }));
await b.close();
